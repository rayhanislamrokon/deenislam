function normalize(value) {
  return String(value || "")
    .toLowerCase()
    .normalize("NFKC");
}
function termMatches(text, term) {
  if (/^[a-z0-9' ]+$/.test(term))
    return new RegExp("(?:^|[^a-z0-9])" + term + "(?:$|[^a-z0-9])", "i").test(
      text,
    );
  return text.includes(term);
}
function classifyIslamicScope(
  question,
  appContext = "",
  databaseRelevant = false,
) {
  const text = normalize(question),
    matchedTerms = ISLAMIC_TERMS.filter((term) => termMatches(text, term));
  const phraseMatch = ISLAMIC_PHRASES.some((pattern) => pattern.test(text));
  const negativeMatch = CLEARLY_NON_ISLAMIC.some((pattern) =>
    pattern.test(text),
  );
  const contextRelevant =
    Boolean(String(appContext || "").trim()) || Boolean(databaseRelevant);
  if (matchedTerms.length || phraseMatch || (contextRelevant && !negativeMatch))
    return {
      allowed: true,
      reason: matchedTerms.length
        ? "keyword"
        : phraseMatch
          ? "semantic-rule"
          : "library-relevance",
    };
  return {
    allowed: false,
    reason: negativeMatch
      ? "clear-out-of-scope"
      : "insufficient-islamic-signal",
  };
}
