async function seedIslamicHistory(collection) {
  const now = new Date();
  await collection.bulkWrite(
    periods.map(([slug, range, title, subtitle, summary, titles], index) => ({
      updateOne: {
        filter: { slug },
        update: {
          $setOnInsert: {
            slug,
            range,
            title,
            subtitle,
            summary,
            order: index + 1,
            published: true,
            translations: {},
            chapters: titles.map((chapterTitle, chapterIndex) => ({
              title: chapterTitle,
              content: summary,
              about: `This topic belongs to the ${title} period and is part of the Deen Islam History curriculum.`,
              reference: "",
              order: chapterIndex + 1,
            })),
            createdAt: now,
            updatedAt: now,
          },
        },
        upsert: true,
      },
    })),
    { ordered: false },
  );
}
module.exports = { seedIslamicHistory, periods };
