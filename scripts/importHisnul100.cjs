const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const input = JSON.parse(fs.readFileSync(path.join(root, '.tmp-hisnul-muslim.json'), 'utf8'));
const existingFiles = ['zikrPresets.ts', 'additionalDuas.ts', 'moreDuas.ts'];
const normalizeArabic = value => String(value || '').normalize('NFKD').replace(/[\u064B-\u065F\u0670\u06D6-\u06ED\sـ]/g, '');
const existing = new Set();

for (const file of existingFiles) {
  const source = fs.readFileSync(path.join(root, 'src', 'data', file), 'utf8');
  const tree = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
  const visit = node => {
    if ((ts.isArrayLiteralExpression(node) || ts.isCallExpression(node)) && node.getChildCount()) {
      const values = ts.isArrayLiteralExpression(node) ? node.elements : node.arguments;
      if (values.length > 1 && (ts.isStringLiteral(values[1]) || ts.isNoSubstitutionTemplateLiteral(values[1]))) {
        const value = values[1].text;
        if (/\p{Script=Arabic}/u.test(value)) existing.add(normalizeArabic(value));
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(tree);
}

const all = [];
for (const segment of input.segments || []) {
  for (const category of segment.categories || []) {
    for (const title of category.titles || []) {
      for (const item of title.duas || []) {
        all.push({
          label: String(title.title_name || category.category_name || 'Daily Dua').trim(),
          category: String(category.category_name || segment.segment_name || '').trim(),
          arabic: String(item.arabic || '').trim(),
          pronunciation: String(item.latin || '').trim(),
          meaning: String(item.translation || '').trim(),
          source: String(item.source || '').trim(),
        });
      }
    }
  }
}

const seen = new Set(existing);
const selected = [];
for (const item of all) {
  const key = normalizeArabic(item.arabic);
  if (!key || !item.pronunciation || !item.meaning || seen.has(key)) continue;
  seen.add(key);
  selected.push(item);
  if (selected.length === 100) break;
}
if (selected.length !== 100) throw new Error(`Expected 100 unique duas, found ${selected.length}`);

const titleCounts = new Map();
for (const item of selected) titleCounts.set(item.label, (titleCounts.get(item.label) || 0) + 1);
const titleIndexes = new Map();
for (const item of selected) {
  if (titleCounts.get(item.label) > 1) {
    const next = (titleIndexes.get(item.label) || 0) + 1;
    titleIndexes.set(item.label, next);
    item.label = `${item.label} ${next}`;
  }
}

const rows = selected.map(item => `  ${JSON.stringify({
  label: item.label,
  arabic: item.arabic,
  meaning: item.meaning,
  names: [item.label, item.pronunciation],
  source: item.source,
})},`).join('\n');
const output = `import type { ZikrPreset } from './zikrPresets';\n\n// Offline Hisnul Muslim collection; generated by scripts/importHisnul100.cjs.\nexport const HISNUL_MUSLIM_100: ZikrPreset[] = [\n${rows}\n];\n`;
fs.writeFileSync(path.join(root, 'src', 'data', 'hisnulMuslim100.ts'), output, 'utf8');
console.log(`Generated ${selected.length} unique duas.`);
